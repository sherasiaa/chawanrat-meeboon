# ==========================================
# โจทย์ข้อที่ 1: คำนวณเงินทอน
# Input: บรรทัดที่ 1 จำนวนเงินที่จ่าย (pay), บรรทัดที่ 2 ราคาสินค้า (price) [จำนวนเต็ม]
# Output: จำนวนเงินทอน (pay - price)
# ==========================================


# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
pay = int(input("จำนวนเงินที่จ่าย "))
price = int(input("ราคาสินค้า "))
net_price = pay-price
print(f"จำนวนเงินทอน {net_price}")
